"""Turn the hard macros (pad cells, SRAM) into matching black boxes for LVS.

Usage: blackbox_macros.py <layout.spice> <netlist.v>   (both rewritten in place)

Run after strip_power_pins.py, so the macro subckts already carry only the
pins the gate-level netlist connects. This script then:
  * empties each macro subckt body in the layout SPICE (their internals are
    signed off by the macro / IO-library vendor, and Magic only has an
    abstract or hierarchy-only view of them anyway),
  * deletes every subckt no longer reachable from the top cell,
  * puts the macro pins into one canonical order (base name, bus index
    descending), permuting each instance's connections to match, and
  * appends a port-only Verilog module per macro with the same order, so
    Netgen sees the same empty cell on both sides and compares only how the
    rest of the design connects to it.
"""
import re
import sys

MACRO_PREFIXES = ("sky130_ef_io__", "sky130_sram_")


def read_statements(text):
    """SPICE logical lines (continuations joined)."""
    stmts = []
    for line in text.split("\n"):
        if line.startswith("+") and stmts:
            stmts[-1] += " " + line[1:].strip()
        else:
            stmts.append(line.rstrip())
    return stmts


def wrap(tokens, width=8):
    first, rest = tokens[:width], tokens[width:]
    out = [" ".join(first)]
    while rest:
        out.append("+ " + " ".join(rest[:width]))
        rest = rest[width:]
    return out


def split_bus(pin):
    m = re.match(r"^(.*)\[(\d+)\]$", pin)
    return (m.group(1), int(m.group(2))) if m else (pin, None)


def canonical(pins):
    """Sort by base name, bus index descending (the order a Verilog
    `[hi:lo] name` port expands to)."""
    def key(p):
        base, idx = split_bus(p)
        return (base, -(idx if idx is not None else -1))
    return sorted(pins, key=key)


def main():
    spice_path, v_path = sys.argv[1], sys.argv[2]
    stmts = read_statements(open(spice_path).read())

    # Pass 1: subckt headers, instance masters.
    subckts = {}   # name -> (pins, body statements)
    order = []
    top_level = []
    cur = None
    for s in stmts:
        low = s.strip().lower()
        if low.startswith(".subckt"):
            t = s.split()
            cur = t[1]
            subckts[cur] = [t[2:], []]
            order.append(cur)
        elif low.startswith(".ends"):
            cur = None
        elif cur is not None:
            subckts[cur][1].append(s)
        else:
            top_level.append(s)

    def inst_master(s):
        return s.split()[-1] if s.startswith("X") else None

    top = None
    for name in subckts:
        if name == "picorv32_top":
            top = name
    if top is None:
        sys.exit("ERROR: top subckt picorv32_top not found in layout SPICE")

    used_macros = {inst_master(s) for s in subckts[top][1] if inst_master(s)}
    macros = sorted(m for m in used_macros if m.startswith(MACRO_PREFIXES) and m in subckts)

    # Reachability from the top over the original logical statements; macros
    # are leaves (their bodies are about to be emptied).
    keep, todo = set(), [top]
    while todo:
        n = todo.pop()
        if n in keep or n not in subckts:
            continue
        keep.add(n)
        if n in macros:
            continue
        for s in subckts[n][1]:
            mm = inst_master(s)
            if mm:
                todo.append(mm)

    # Pass 2: canonical pin order per macro, permute instances in the top cell.
    new_pins = {}
    for m in macros:
        new_pins[m] = canonical(subckts[m][0])
    new_body = []
    for s in subckts[top][1]:
        mm = inst_master(s)
        if mm in new_pins:
            t = s.split()
            nets = t[1:-1]
            old = subckts[mm][0]
            if len(nets) != len(old):
                sys.exit(f"ERROR: {t[0]} has {len(nets)} connections, {mm} declares {len(old)} pins")
            by_pin = dict(zip(old, nets))
            t = [t[0]] + [by_pin[p] for p in new_pins[mm]] + [mm]
            new_body.extend(wrap(t))
        else:
            new_body.append(s)
    subckts[top][1] = new_body
    for m in macros:
        subckts[m] = [new_pins[m], []]

    out = list(top_level)
    for n in order:
        if n not in keep:
            continue
        pins, body = subckts[n]
        out.extend(wrap([".subckt", n] + pins))
        out.extend(body)
        out.append(".ends")
        out.append("")
    open(spice_path, "w").write("\n".join(out) + "\n")

    # Verilog stubs, same order. Bus pins become one vector port each.
    stubs = ["", "// Black-box stubs for LVS (generated by blackbox_macros.py)."]
    for m in macros:
        ports, widths = [], {}
        for p in new_pins[m]:
            base, idx = split_bus(p)
            if base not in widths:
                ports.append(base)
                widths[base] = None
            if idx is not None:
                widths[base] = idx if widths[base] is None else max(widths[base], idx)
        stubs.append(f"module {m} ({', '.join(ports)});")
        for b in ports:
            hi = widths[b]
            stubs.append(f"  inout [{hi}:0] {b};" if hi is not None else f"  inout {b};")
        stubs.append("endmodule")
    with open(v_path, "a") as f:
        f.write("\n".join(stubs) + "\n")
    print(f"Blackboxed {len(macros)} macro cell(s): {macros}; kept {len(keep)} subckts in layout SPICE")


if __name__ == "__main__":
    main()
